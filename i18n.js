let LANG = "en";
const I18N_RERENDER = [];

function t(key, vars) {
  const dict = I18N[LANG] || I18N.en;
  let s = (dict && dict[key] !== undefined) ? dict[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
  if (vars) for (const k of Object.keys(vars)) s = s.split("{" + k + "}").join(vars[k]);
  return s;
}

function applyStaticI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.getAttribute("data-i18n")); });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.getAttribute("data-i18n-ph")); });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.getAttribute("data-i18n-title")); });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria"))); });
}

function updateLangSwitcher() {
  const names = { en: "English", mr: "मराठी", hi: "हिन्दी" };
  const label = document.getElementById("lang-label");
  if (label) label.textContent = names[LANG] || "English";
}

function setLang(lang) {
  if (!I18N[lang]) lang = "en";
  LANG = lang;
  try { localStorage.setItem("bm_lang", lang); } catch (e) {}
  document.documentElement.lang = lang;
  applyStaticI18n();
  updateLangSwitcher();
  I18N_RERENDER.forEach((fn) => { try { fn(); } catch (e) {} });
}

function initLang() {
  let saved = "en";
  try { saved = localStorage.getItem("bm_lang") || "en"; } catch (e) {}
  LANG = I18N[saved] ? saved : "en";
  document.documentElement.lang = LANG;
}
